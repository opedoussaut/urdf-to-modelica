"""Expand the pinned Interbotix ALOHA xacro files into plain URDF (deterministic, no ROS install).

Produces, under data/urdf/:
  aloha_vx300s_<side>.urdf / aloha_wx250s_<side>.urdf   one file per physical arm
  aloha_stationary.urdf                                 the 4-arm workcell, each arm fixed to `world`
                                                        with the static transforms of aloha_bringup.launch.py

`$(find pkg)` is resolved against third_party/ instead of ament_index.
"""
import hashlib
import json
import re
import sys
from pathlib import Path
from xml.etree import ElementTree as ET

import xacro
from xacro import substitution_args

ROOT = Path(__file__).resolve().parents[1]
PKG_ROOT = ROOT / "third_party/interbotix_ros_manipulators/interbotix_ros_xsarms"
DESC = PKG_ROOT / "interbotix_xsarm_descriptions"
OUT = ROOT / "data/urdf"

substitution_args._eval_find = lambda pkg: str(PKG_ROOT / pkg)

# Static transforms published by Interbotix/aloha launch/aloha_bringup.launch.py
# (x, y, z, qx, qy, qz, qw) world -> <robot_name>/base_link
ARMS = [
    ("follower_left", "aloha_vx300s", (0.5, 0.25, 0.0)),
    ("follower_right", "aloha_vx300s", (0.5, -0.25, 0.0)),
    ("leader_left", "aloha_wx250s", (-0.5, 0.25, 0.0)),
    ("leader_right", "aloha_wx250s", (-0.5, -0.25, 0.0)),
]


def expand(model: str, robot_name: str) -> str:
    src = DESC / "urdf" / f"{model}.urdf.xacro"
    doc = xacro.process_file(str(src), mappings={"robot_name": robot_name})
    return doc.toprettyxml(indent="  ")


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    world = ET.Element("robot", name="aloha_stationary")
    world.append(ET.Comment(
        " Generated by tools/expand_xacro.py from pinned Interbotix sources; do not edit. "))
    ET.SubElement(world, "link", name="world")
    record = {"generator": "tools/expand_xacro.py", "arms": []}
    # One generic URDF per arm model (robot_name == model) used to generate reusable arm classes.
    for model in sorted({m for _, m, _ in ARMS}):
        (OUT / f"{model}.urdf").write_text(expand(model, model), encoding="utf-8")
    for robot_name, model, xyz in ARMS:
        text = expand(model, robot_name)
        f = OUT / f"{robot_name}.urdf"
        f.write_text(text, encoding="utf-8")
        arm = ET.fromstring(text.encode())
        j = ET.SubElement(world, "joint", name=f"{robot_name}_mount", type="fixed")
        ET.SubElement(j, "parent", link="world")
        ET.SubElement(j, "child", link=f"{robot_name}/base_link")
        ET.SubElement(j, "origin", xyz=" ".join(map(str, xyz)), rpy="0 0 0")
        # Interbotix namespaces link names with robot_name but not joint names; namespace them
        # so the 4-arm assembly has unique joint identifiers.
        for jt in arm.iter("joint"):
            jt.set("name", f"{robot_name}/{jt.get('name')}")
        for m in arm.iter("mimic"):
            m.set("joint", f"{robot_name}/{m.get('joint')}")
        for el in arm:
            if el.tag in ("link", "joint", "material"):
                if el.tag == "material" and world.find(f"material[@name='{el.get('name')}']") is not None:
                    continue
                world.append(el)
        record["arms"].append({
            "robot_name": robot_name, "model": model, "mount_xyz": xyz,
            "xacro": str((DESC / "urdf" / f"{model}.urdf.xacro").relative_to(ROOT)).replace("\\", "/"),
            "xacro_sha256": sha256(DESC / "urdf" / f"{model}.urdf.xacro"),
            "urdf": str(f.relative_to(ROOT)).replace("\\", "/"),
        })
    ET.indent(world)
    combined = OUT / "aloha_stationary.urdf"
    combined.write_text(ET.tostring(world, encoding="unicode"), encoding="utf-8")
    record["combined_urdf"] = "data/urdf/aloha_stationary.urdf"
    record["combined_sha256"] = sha256(combined)
    (OUT / "expansion_record.json").write_text(json.dumps(record, indent=2))
    n_links = len(world.findall("link"))
    n_joints = len(world.findall("joint"))
    print(f"combined: {n_links} links, {n_joints} joints -> {combined}")


if __name__ == "__main__":
    sys.exit(main())
