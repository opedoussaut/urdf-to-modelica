"""Expand the pinned Interbotix ALOHA xacro files into plain URDF (deterministic, no ROS install).

Produces, under data/urdf/:
  aloha_vx300s.urdf, aloha_wx250s.urdf   generic per-model URDF (link names prefixed with the model name)
  aloha2_bimanual.urdf                   ALOHA 2 robot: two followers fixed to `world` at the mount poses of the
                                         official ALOHA 2 MJCF (mujoco_menagerie/aloha/aloha.xml)

`$(find pkg)` is resolved against third_party/ instead of ament_index.
"""
import hashlib
import json
import sys
from pathlib import Path
from xml.etree import ElementTree as ET

import xacro
from xacro import substitution_args

ROOT = Path(__file__).resolve().parents[1]
PKG_ROOT = ROOT / "third_party/interbotix_ros_manipulators/interbotix_ros_xsarms"
DESC = PKG_ROOT / "interbotix_xsarm_descriptions"
OUT = ROOT / "data/urdf"

substitution_args._eval_find = lambda pkg: str(PKG_ROOT / pkg)

MODELS = ["aloha_vx300s", "aloha_wx250s"]
# mujoco_menagerie/aloha/aloha.xml @62ab00f: left/base_link pos="-0.469 -0.019 0.02";
# right/base_link pos="0.469 -0.019 0.02" quat="0 0 0 1" (180 deg about z)
ARMS = [
    ("follower_left", "aloha_vx300s", (-0.469, -0.019, 0.02), (0.0, 0.0, 0.0)),
    ("follower_right", "aloha_vx300s", (0.469, -0.019, 0.02), (0.0, 0.0, 3.141592653589793)),
]


def expand(model: str, robot_name: str) -> str:
    src = DESC / "urdf" / f"{model}.urdf.xacro"
    doc = xacro.process_file(str(src), mappings={"robot_name": robot_name})
    return doc.toprettyxml(indent="  ")


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in OUT.glob("*.urdf"):
        stale.unlink()
    for model in MODELS:
        (OUT / f"{model}.urdf").write_text(expand(model, model), encoding="utf-8")

    world = ET.Element("robot", name="aloha2_bimanual")
    world.append(ET.Comment(" Generated by tools/expand_xacro.py from pinned Interbotix sources; do not edit. "))
    ET.SubElement(world, "link", name="world")
    record = {"generator": "tools/expand_xacro.py", "models": {}, "arms": []}
    for model in MODELS:
        x = DESC / "urdf" / f"{model}.urdf.xacro"
        record["models"][model] = {"xacro": x.relative_to(ROOT).as_posix(), "xacro_sha256": sha256(x),
                                   "urdf": f"data/urdf/{model}.urdf", "urdf_sha256": sha256(OUT / f"{model}.urdf")}
    for robot_name, model, xyz, rpy in ARMS:
        arm = ET.fromstring(expand(model, robot_name).encode())
        j = ET.SubElement(world, "joint", name=f"{robot_name}_mount", type="fixed")
        ET.SubElement(j, "parent", link="world")
        ET.SubElement(j, "child", link=f"{robot_name}/base_link")
        ET.SubElement(j, "origin", xyz=" ".join(map(str, xyz)), rpy=" ".join(map(str, rpy)))
        # Interbotix namespaces link names with robot_name but not joint names; namespace them.
        for jt in arm.iter("joint"):
            jt.set("name", f"{robot_name}/{jt.get('name')}")
        for m in arm.iter("mimic"):
            m.set("joint", f"{robot_name}/{m.get('joint')}")
        for el in arm:
            if el.tag in ("link", "joint", "material"):
                if el.tag == "material" and world.find(f"material[@name='{el.get('name')}']") is not None:
                    continue
                world.append(el)
        record["arms"].append({"robot_name": robot_name, "model": model, "mount_xyz": xyz, "mount_rpy": rpy})
    ET.indent(world)
    combined = OUT / "aloha2_bimanual.urdf"
    combined.write_text(ET.tostring(world, encoding="unicode"), encoding="utf-8")
    record["combined_urdf"] = "data/urdf/aloha2_bimanual.urdf"
    record["combined_sha256"] = sha256(combined)
    (OUT / "expansion_record.json").write_text(json.dumps(record, indent=2))
    print(f"combined: {len(world.findall('link'))} links, {len(world.findall('joint'))} joints -> {combined}")


if __name__ == "__main__":
    sys.exit(main())
