import { useEffect, useState } from "react";
import { Cpu, FileCode2, CheckCircle2, XCircle, ShieldCheck, Import, AlertTriangle } from "lucide-react";
import { message, request, waitJob, type Context, type Doc } from "./studio";

const STAGE_HELP: Record<string, string> = {
  "1": "Allowlisted pinned file, SHA-256 recorded before conversion.",
  "2": "URDF parsed by kkh.engineering.urdf_model: tree, joints, limits, mimic, inertials.",
  "3": "The project's deterministic converter writes a NEW package into an isolated run directory.",
  "4": "URDF joint → generated Modelica component, modifiers and mimic equations.",
  "5": "Independent inspection of the generated class against the URDF (links, joints, axes, limits).",
  "6": "Real OpenModelica 1.27.1 loadFile + checkModel on the new package.",
  "7": "Sources and frozen package re-hashed; generated bytes compared with the preserved package.",
};

export default function ModelPipeline({
  setContext,
  open,
}: {
  context: Context;
  setContext: (c: Partial<Context>) => void;
  open: (i: number) => void;
}) {
  const [sources, setSources] = useState<any>(),
    [source, setSource] = useState("aloha2"),
    [run, setRun] = useState<Doc>(),
    [runs, setRuns] = useState<any[]>([]),
    [busy, setBusy] = useState(false),
    [started, setStarted] = useState(0),
    [tick, setTick] = useState(0),
    [code, setCode] = useState<{ path: string; text: string }>(),
    [error, setError] = useState(""),
    [notice, setNotice] = useState("");
  useEffect(() => {
    request("/lab/pipeline/sources").then(setSources).catch((e) => setError(message(e)));
    request<any[]>("/lab/pipeline/runs").then(setRuns).catch(() => {});
    const id = new URLSearchParams(location.search).get("run");
    if (id) request<Doc>("/record/" + id).then(setRun).catch((e) => setError(message(e)));
  }, []);
  useEffect(() => {
    if (!busy) return;
    const t = setInterval(() => setTick((n) => n + 1), 500);
    return () => clearInterval(t);
  }, [busy]);
  void tick;
  const selected = sources?.sources.find((s: any) => s.id === source);
  const arm = selected?.arms.find((a: any) => a.model === "aloha_vx300s") || selected?.arms[0];

  const generate = async () => {
    setBusy(true);
    setStarted(Date.now());
    setError("");
    setNotice("");
    setCode(undefined);
    try {
      const record = await waitJob(await request("/lab/pipeline/run", "POST", { source }));
      setRun(record);
      request<any[]>("/lab/pipeline/runs").then(setRuns).catch(() => {});
    } catch (e) {
      setError(message(e));
    } finally {
      setBusy(false);
    }
  };
  const openRun = (id: string) => request<Doc>("/record/" + id).then(setRun).catch((e) => setError(message(e)));
  const showFile = (path: string) =>
    run && request("/lab/pipeline/" + run.id + "/file?path=" + encodeURIComponent(path)).then(setCode).catch((e) => setError(message(e)));
  const importModel = async () => {
    if (!run || !confirm("Create a NEW editable model workspace from this freshly generated package? The frozen baseline and existing models are not changed.")) return;
    try {
      const w = await request<Doc>("/lab/pipeline/" + run.id + "/import", "POST", { name: `Generated candidate ${run.id.slice(0, 8)}`, confirm: true });
      setContext({ model: w.id, model_revision: w.data.head, file: "Arms/AlohaVX300s.mo", selected: "shoulder", robot: "aloha_vx300s" });
      setNotice(`Editable model ${w.id.slice(0, 8)} created from the generated package. Open it in the Modelica editor.`);
    } catch (e) {
      setError(message(e));
    }
  };
  const stage = (n: string) => run?.data.stages.find((s: any) => s.stage.startsWith(n));
  const mapping = stage("4")?.result,
    completeness = stage("5")?.result,
    check = stage("6")?.result,
    integrity = stage("7")?.result,
    generated = stage("3")?.result;

  return (
    <div className="lab">
      <header className="lab-head">
        <div>
          <span className="lab-eyebrow">ROBOT MODEL PIPELINE · URDF → MODELICA</span>
          <h1>Derive the Modelica model from the robot description</h1>
          <p>
            Runs the project's deterministic converter on a pinned ALOHA URDF, writes a new package into an isolated run
            directory, maps every URDF element, and checks the result with OpenModelica. The frozen package is never
            overwritten.
          </p>
        </div>
      </header>
      {error && <div className="lab-alert error">{error}</div>}
      {notice && (
        <div className="lab-alert info">
          {notice}{" "}
          <button className="lab-link" onClick={() => open(1)}>
            Open the Modelica editor →
          </button>
        </div>
      )}

      <section className="lab-card">
        <div className="lab-card-head">
          <h2>1 · Choose the source</h2>
          <span className="lab-tag">allowlisted pinned files only</span>
        </div>
        <div className="lab-sources">
          {sources?.sources.map((s: any) => (
            <button key={s.id} className={"lab-source" + (s.id === source ? " on" : "")} aria-pressed={s.id === source} onClick={() => setSource(s.id)}>
              <b>{s.label}</b>
              {s.files_detail.map((f: any) => (
                <small key={f.path}>
                  {f.path} · sha256 {f.sha256.slice(0, 12)}… · {(f.bytes / 1024).toFixed(1)} kB
                </small>
              ))}
              <em>interface: {s.interface}</em>
            </button>
          ))}
        </div>
        {sources && <p className="lab-footnote">{sources.note} Upstream: {sources.provenance.descriptions}.</p>}
        {arm && (
          <>
            <div className="lab-kpis compact">
              {(
                [
                  ["links", "Links"],
                  ["joints", "Joints"],
                  ["moving", "Moving"],
                  ["fixed", "Fixed"],
                  ["mimic", "Mimic"],
                  ["total_mass_kg", "URDF mass (kg)"],
                ] as const
              ).map(([k, l]) => (
                <div key={k} className="lab-kpi">
                  <span>{l}</span>
                  <b>{arm[k]}</b>
                </div>
              ))}
            </div>
            <p className="lab-footnote">
              {arm.product} · placeholder inertials (rendered massless, not invented): {arm.placeholder_links.join(", ") || "none"}.
            </p>
            <details className="lab-history">
              <summary>URDF joint table · {arm.model}</summary>
              <table className="lab-table">
                <thead>
                  <tr>
                    <th>Joint</th>
                    <th>Type</th>
                    <th>Parent → child</th>
                    <th>Axis</th>
                    <th>Limits</th>
                    <th>Mimic</th>
                  </tr>
                </thead>
                <tbody>
                  {arm.joint_table.map((j: any) => (
                    <tr key={j.name} className={["shoulder", "right_finger", "left_finger"].includes(j.name) ? "hl" : ""}>
                      <td>{j.name}</td>
                      <td>{j.type}</td>
                      <td>
                        {j.parent} → {j.child}
                      </td>
                      <td>{j.axis.join(", ")}</td>
                      <td>{j.lower !== null ? `[${(+j.lower).toFixed(4)}, ${(+j.upper).toFixed(4)}] ${j.unit}` : "—"}</td>
                      <td>{j.mimic ? `${j.mimic.multiplier} × ${j.mimic.joint} + ${j.mimic.offset}` : ""}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </details>
          </>
        )}
        <div className="lab-actions">
          <button className="lab-primary" disabled={busy || !sources} onClick={generate}>
            <Cpu size={15} /> Generate Modelica candidate
          </button>
          {busy && (
            <span className="lab-status running">
              <span className="lab-spinner" /> converter + OpenModelica running… {((Date.now() - started) / 1000).toFixed(0)} s
            </span>
          )}
        </div>
      </section>

      {run && (
        <>
          <section className="lab-card">
            <div className="lab-card-head">
              <h2>
                2 · Pipeline run {run.id.slice(0, 8)} {run.data.ok ? <span className="lab-badge verified">all stages passed</span> : <span className="lab-badge fail">failed</span>}
              </h2>
              <span className="lab-tag">{new Date(run.data.started).toLocaleString()} · {run.data.output_root}</span>
            </div>
            <ol className="lab-stages">
              {run.data.stages.map((s: any) => (
                <li key={s.stage} className={s.ok ? "ok" : "fail"}>
                  {s.ok ? <CheckCircle2 size={16} /> : <XCircle size={16} />}
                  <div>
                    <b>{s.stage}</b> <small>{s.seconds} s</small>
                    <p>{STAGE_HELP[s.stage[0]]}</p>
                    {s.error && <pre>{s.error}</pre>}
                  </div>
                </li>
              ))}
            </ol>
            {generated && (
              <p className="lab-footnote">
                Interface <code>{run.data.interface}</code> · generator v{generated.generator_version} · {generated.files} files written to{" "}
                <code>{generated.package}</code>
              </p>
            )}
          </section>

          {mapping && (
            <section className="lab-card">
              <div className="lab-card-head">
                <h2>3 · URDF ↔ Modelica correspondence</h2>
                <span className="lab-tag">read from the newly generated class</span>
              </div>
              {Object.entries(mapping).map(([model, m]: any) => (
                <div key={model} className="lab-mapping">
                  <h3>
                    {model} → <button className="lab-link" onClick={() => showFile(m.class_file.replace("ALOHA2/", ""))}>{m.class_file}</button>
                  </h3>
                  <table className="lab-table">
                    <thead>
                      <tr>
                        <th>URDF joint</th>
                        <th>Axis · limits · mimic (URDF)</th>
                        <th>Generated component</th>
                        <th>Modelica modifiers</th>
                      </tr>
                    </thead>
                    <tbody>
                      {m.rows.map((r: any) => (
                        <tr key={r.urdf_joint}>
                          <td>
                            <b>{r.urdf_joint}</b> <small>{r.type}</small>
                          </td>
                          <td>
                            n = [{r.axis.join(", ")}] · [{r.limits?.map((v: number) => v.toFixed(4)).join(", ")}] {r.type === "prismatic" ? "m" : "rad"}
                            {r.mimic && (
                              <>
                                <br />
                                <b>mimic: {r.mimic.multiplier} × {r.mimic.joint} + {r.mimic.offset}</b>
                              </>
                            )}
                          </td>
                          <td>
                            <code>{r.modelica_component}</code>
                            <br />
                            <small>{r.modelica_type}</small>
                          </td>
                          <td className="mono">
                            {Object.entries(r.modifiers)
                              .filter(([k]) => ["n", "q_min", "q_max", "s_min", "s_max", "tau_max", "f_max"].includes(k))
                              .map(([k, v]) => `${k} = ${v}`)
                              .join(" · ")}
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                  {m.mimic_equations.length > 0 && (
                    <p className="lab-footnote">
                      Mimic equations in the generated class: <code>{m.mimic_equations.join("  ")}</code> — the URDF multiplier −1 is
                      preserved (sign errors here are caught by the ontology mimic rule; see Engineering Reasoning).
                    </p>
                  )}
                </div>
              ))}
              <p className="lab-footnote">
                The generated arm classes are prescribed-motion MultiBody models (kinematics, masses, inertias, limits). Servo
                gains are not derived from URDF: they live in <code>ALOHA2.Control</code> as assumed parameters.
              </p>
            </section>
          )}

          <div className="lab-grid">
            {completeness && (
              <section className="lab-card">
                <div className="lab-card-head">
                  <h2>4 · Completeness</h2>
                  <span className="lab-tag">modelica_inspect</span>
                </div>
                <table className="lab-table">
                  <thead>
                    <tr>
                      <th>Class</th>
                      <th>Links</th>
                      <th>Joints</th>
                      <th>Axes</th>
                      <th>Limits</th>
                      <th>Issues</th>
                    </tr>
                  </thead>
                  <tbody>
                    {Object.values(completeness).map((c: any) => (
                      <tr key={c.class}>
                        <td>{c.class}</td>
                        <td>{c.links}</td>
                        <td>{c.joints}</td>
                        <td>{(c.axis_correctness * 100).toFixed(0)} %</td>
                        <td>{(c.limit_coverage * 100).toFixed(0)} %</td>
                        <td>{c.issues.length || "none"}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </section>
            )}
            {check && (
              <section className="lab-card">
                <div className="lab-card-head">
                  <h2>5 · OpenModelica check</h2>
                  <span className="lab-tag">{check.omc}</span>
                </div>
                <ul className="lab-checks">
                  {Object.entries(check.checks).map(([cls, c]: any) => (
                    <li key={cls} className={c.ok ? "ok" : "fail"}>
                      {c.ok ? <CheckCircle2 size={15} /> : <XCircle size={15} />} <code>{cls}</code> · {c.equations} equations / {c.variables} variables
                    </li>
                  ))}
                </ul>
                <p className="lab-footnote">Command: {check.command}. A successful check proves structural consistency, not physical calibration.</p>
              </section>
            )}
          </div>

          {integrity && (
            <section className="lab-card">
              <div className="lab-card-head">
                <h2>
                  <ShieldCheck size={17} /> 6 · Integrity &amp; reproducibility
                </h2>
              </div>
              <div className="lab-kpis compact">
                <div className={"lab-kpi " + (integrity.sources_unchanged ? "improved" : "worse")}>
                  <span>Pinned URDF unchanged</span>
                  <b>{integrity.sources_unchanged ? "yes" : "NO"}</b>
                </div>
                <div className={"lab-kpi " + (integrity.frozen_package_unchanged ? "improved" : "worse")}>
                  <span>Frozen package unchanged</span>
                  <b>{integrity.frozen_package_unchanged ? "yes" : "NO"}</b>
                </div>
                <div className="lab-kpi">
                  <span>Generated files identical to preserved package</span>
                  <b>{integrity.generated_files_identical_to_frozen}</b>
                </div>
              </div>
              <p className="lab-footnote">{integrity.note}</p>
              <div className="lab-actions">
                <button className="lab-primary" disabled={run.data.source !== "aloha2" || !run.data.ok} onClick={importModel}>
                  <Import size={14} /> Import as new editable model…
                </button>
                {run.data.source !== "aloha2" && (
                  <small className="lab-footnote">
                    <AlertTriangle size={12} /> Single-arm candidates are for inspection; import uses the full ALOHA 2 package.
                  </small>
                )}
              </div>
            </section>
          )}
          {code && (
            <section className="lab-card">
              <div className="lab-card-head">
                <h2>
                  <FileCode2 size={17} /> {code.path} (generated, read-only)
                </h2>
                <button className="lab-ghost" onClick={() => setCode(undefined)}>
                  Close
                </button>
              </div>
              <pre className="lab-code tall">{code.text}</pre>
            </section>
          )}
        </>
      )}
      <details className="lab-history">
        <summary>Previous pipeline runs ({runs.length})</summary>
        <ul>
          {runs.map((r) => (
            <li key={r.id}>
              <button className="lab-link" onClick={() => openRun(r.id)}>
                {new Date(r.created).toLocaleString()} · {r.source} · {r.ok ? "passed" : "failed"} · {r.id.slice(0, 8)}
              </button>
            </li>
          ))}
        </ul>
      </details>
    </div>
  );
}
